// Keeps renamed products reachable at their old URLs.
// Runs before every build. Google has these indexed; a 404 throws away the ranking.
import { readFileSync, writeFileSync, readdirSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');

// old slug -> current slug. Never delete a line from here; a redirect is permanent.
const RENAMES = {
  'neakasa-m1': 'neakasa-m1-plus',
  'catlink-scooper-pro-x': 'catlink-ultra',
  'catlink-luxury-pro': 'catlink-luxury-pro-x',
  'petsafe-scoopfree-smart': 'petsafe-scoopfree-smartspin',
};

const slugs = readdirSync(join(root, 'src/data/products'))
  .filter((f) => f.endsWith('.json'))
  .map((f) => f.replace(/\.json$/, ''));

const pair = (a, b) => [a, b].sort().join('-vs-');

const redirects = {};
for (const [from, to] of Object.entries(RENAMES)) {
  redirects['/reviews/' + from + '/'] = '/reviews/' + to + '/';
  redirects['/troubleshooting/' + from + '/'] = '/troubleshooting/' + to + '/';

  // Every comparison page that used the old slug moves with it.
  for (const other of slugs) {
    if (other === to) continue;
    const oldPair = pair(from, other);
    const newPair = pair(to, other);
    if (oldPair === newPair) continue;
    redirects['/compare/' + oldPair + '/'] = '/compare/' + newPair + '/';
  }
}

mkdirSync(join(root, 'src/data'), { recursive: true });
writeFileSync(join(root, 'src/data/redirects.json'), JSON.stringify(redirects, null, 2) + '\n');

// Hosts that understand _redirects give a real 301; Astro's generated pages cover
// the rest. Belt and braces, because losing these would cost us indexed pages.
const lines = Object.entries(redirects).map(([from, to]) => from + '  ' + to + '  301');
writeFileSync(
  join(root, 'public/_redirects'),
  '# Generated by scripts/build-redirects.mjs — do not edit by hand\n' + lines.join('\n') + '\n'
);

console.log('Wrote ' + lines.length + ' redirects for ' + Object.keys(RENAMES).length + ' renamed products.');
